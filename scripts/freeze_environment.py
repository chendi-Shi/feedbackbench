"""Capture all installed distributions without embedding private local paths."""
from __future__ import annotations

import importlib.metadata
from pathlib import Path
import re


def main():
    root = Path(__file__).resolve().parents[1]
    records = {}
    for distribution in importlib.metadata.distributions():
        name = distribution.metadata["Name"]
        canonical = re.sub(r"[-_.]+", "-", name).lower()
        if canonical in {"feedbackbench", "lerobot"}:
            continue
        records[canonical] = f"{name}=={distribution.version}"
    header = (
        "# Tested Python 3.12 Windows CPU environment. Generated by freeze_environment.py.\n"
        "# Install through scripts/bootstrap.py: CPU Torch first, then this full snapshot --no-deps.\n"
        "# Linux-only EGL probes are omitted; opencv-python-headless provides cv2.\n"
        "# Upstream source commit is verified by bootstrap.py before installation.\n"
        "-e ./vendor/MINERVA\n"
    )
    destination = root / "requirements-lock.txt"
    destination.write_text(header + "\n".join(records[key] for key in sorted(records)) + "\n", encoding="utf-8")
    print(f"Saved {len(records)} pinned distributions and one pinned local checkout")


if __name__ == "__main__":
    main()
